/* Browser port of backend/cashflow/calculator.py for the server-less public site.
   Python stays the source of truth: testing/cashflow-parity.json is generated by Python
   (tools/build_cashflow_parity.py) and cashflow.test.ts requires this port to match every case.
   Policy cash benefits are never added here (fixed at 0), same as the public contract. */
export const MAX_KRW = 1_000_000_000_000;
export interface CashflowInput {
  monthly_income: number; monthly_rent: number; monthly_fixed_expenses: number;
  other_monthly_expenses: number; user_savings_capacity: number | null;
}
export interface CashflowResult {
  monthly_income: number; essential_monthly_expenses: number; other_monthly_expenses: number;
  total_monthly_expenses: number; policy_benefit_applied: number; total_monthly_income: number;
  disposable_before_policy: number; disposable_after_policy: number;
  user_savings_capacity: number | null; savable_amount: number;
}
function krw(value: unknown, field: string): number {
  if (typeof value !== 'number' || !Number.isSafeInteger(value) || value < 0 || value > MAX_KRW) throw new RangeError(`INVALID_KRW:${field}`);
  return value;
}
export function calculateCashflow(input: CashflowInput): CashflowResult {
  const income = krw(input.monthly_income, 'monthly_income');
  const essential = krw(input.monthly_rent, 'monthly_rent') + krw(input.monthly_fixed_expenses, 'monthly_fixed_expenses');
  const other = krw(input.other_monthly_expenses, 'other_monthly_expenses');
  const capacity = input.user_savings_capacity === null ? null : krw(input.user_savings_capacity, 'user_savings_capacity');
  const expenses = essential + other;
  const benefit = 0;
  const before = income - expenses;
  const after = income + benefit - expenses;
  // A deficit is kept as-is; only the amount that can go to savings is clamped.
  const savable = capacity === null ? Math.max(0, after) : Math.max(0, Math.min(after, capacity));
  return {
    monthly_income: income, essential_monthly_expenses: essential, other_monthly_expenses: other,
    total_monthly_expenses: expenses, policy_benefit_applied: benefit, total_monthly_income: income + benefit,
    disposable_before_policy: before, disposable_after_policy: after,
    user_savings_capacity: capacity, savable_amount: savable,
  };
}
